import React from 'react';

interface ReportCardFooterProps {
  result: any;
  pageNumber?: number;
  totalPages?: number;
}

export const ReportCardFooter: React.FC<ReportCardFooterProps> = ({
  result,
  pageNumber = 1,
  totalPages = 1,
}) => {
  const reportId = result?._id || '—';
  const timestamp = new Date().toLocaleString();

  return (
    <div style={{
      display: 'flex',
      justifyContent: 'space-between',
      alignItems: 'center',
      borderTop: '1px solid #cbd5e1',
      paddingTop: '0.65rem',
      marginTop: '1rem',
      fontSize: '0.68rem',
      color: '#64748b',
      flexWrap: 'wrap',
      gap: '0.5rem'
    }}>
      <div>
        <span>Generated by <strong>Smart School Management System</strong></span>
        <span style={{ margin: '0 0.5rem' }}>•</span>
        <span>{timestamp}</span>
      </div>
      
      <div style={{ display: 'flex', gap: '0.75rem' }}>
        <span><strong>Report ID:</strong> <code>{reportId}</code></span>
        {totalPages > 1 && (
          <span>Page {pageNumber} of {totalPages}</span>
        )}
      </div>
    </div>
  );
};
